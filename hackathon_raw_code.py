"""## Step 4: Build forecasting examples and chronological splits

Each example has an **input date D** and a **target date D+1**. The first five inputs are D's PM2.5, temperature, humidity, precipitation, and wind speed. The value we want to predict, `pm25_tomorrow`, is the measured PM2.5 on the following calendar day.

We create the next-day target before removing incomplete rows. Because the full calendar is preserved, a missing Tuesday cannot accidentally make Wednesday become Monday's “tomorrow.” We keep only examples with complete required inputs and an actual next-day measurement.

We split by **target date**, keeping the order of time:

| Target dates | Role |
| --- | --- |
| Before January 1, 2025 | Training: learn the model parameters. |
| January 1–December 31, 2025 | Validation: compare approaches on later observations. |
| January 1, 2026 onward | Reserved test period; currently used for date exploration without test metrics. |

A random split would mix earlier and later examples, so we use a chronological split to better represent forecasting forward in time. **Data leakage** means supplying information that would not be available when making the forecast. Tomorrow's measured PM2.5, tomorrow's AQI, and tomorrow's observed weather are not prediction inputs.
"""

# Work on a separate copy of the complete daily calendar.
forecast_data = combined.sort_values("date").copy()

# Use the following calendar day's PM2.5 as the prediction target.
forecast_data["pm25_tomorrow"] = forecast_data["pm25"].shift(-1)

# Record the date being predicted so we can split by target date.
forecast_data["target_date"] = (
    forecast_data["date"] + pd.Timedelta(days=1)
)

# Start with today's pollution and today's weather as inputs.
features = [
    "pm25",
    "temperature_c",
    "humidity_pct",
    "precipitation_mm",
    "wind_speed_ms"
]

# Keep only examples with complete inputs and a real next-day measurement.
# Missing pollution is never replaced with zero or an invented target.
model_df = forecast_data.dropna(
    subset=features + ["pm25_tomorrow"]
).copy()

# Split chronologically using the date being predicted.
train_df = model_df[
    model_df["target_date"] < "2025-01-01"
].copy()

validation_df = model_df[
    (model_df["target_date"] >= "2025-01-01")
    & (model_df["target_date"] < "2026-01-01")
].copy()

test_df = model_df[
    model_df["target_date"] >= "2026-01-01"
].copy()

# Check how many forecasting examples are available in each period.
print("Training examples:", len(train_df))
print("Validation examples:", len(validation_df))
print("Test examples:", len(test_df))

# Inspect the input date, target date, and actual next-day pollution.
display(model_df[
    ["date", "target_date", "pm25", "pm25_tomorrow"]
].head())

"""## Step 5: Train Linear Regression and establish a baseline

Linear Regression learns an intercept and a weight for each of the five input features. Its prediction is the intercept plus the weighted sum of those inputs. The weights are learned from the training period; they are not manually chosen using the validation answers.

We compare it with the **persistence baseline**, which predicts that tomorrow's PM2.5 will equal today's PM2.5. Persistence needs no model training and gives us a useful reference for deciding whether a more complex approach adds value.

This cell reports **mean absolute error (MAE)** on the 2025 validation examples. MAE is the average absolute difference between predicted and measured pollution. Lower is better. An MAE of 2.4 µg/m³ means errors have an average absolute size of approximately 2.4 µg/m³; it does not mean every forecast is within 2.4, and it is not a percentage accuracy.
"""

from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error

# Select the training inputs and the next-day measurements to learn from.
X_train = train_df[features]
y_train = train_df["pm25_tomorrow"]

# Create a Linear Regression model.
model = LinearRegression()

# Train the model using only the training period.
model.fit(X_train, y_train)

# Predict next-day pollution for the validation examples.
validation_predictions = model.predict(validation_df[features])

# Baseline: tomorrow's pollution equals today's pollution.
baseline_predictions = validation_df["pm25"]

# Get the actual next-day measurements for those same examples.
actual = validation_df["pm25_tomorrow"]

# Compare both approaches using mean absolute error.
baseline_mae = mean_absolute_error(actual, baseline_predictions)
model_mae = mean_absolute_error(actual, validation_predictions)

# Lower MAE means smaller prediction errors on average.
print(f"Validation baseline MAE: {baseline_mae:.2f} µg/m³")
print(f"Validation Linear Regression MAE: {model_mae:.2f} µg/m³")

"""## Step 6: Train Random Forest and compare fitting behavior

Random Forest averages predictions from many decision trees. A tree follows rules that divide examples according to their input values. This allows the forest to learn patterns that do not have to follow the single weighted-sum relationship used by Linear Regression.

Our forest uses **300 trees**, a maximum depth of **6**, and at least **5 training examples per leaf**. These limits control tree complexity. The random seed is **42**, which makes repeated runs more reproducible within the same software environment.

The forest trains on the same five features as the individual Linear Regression model. The cell reports persistence, Linear Regression, and Random Forest performance separately for the training and validation periods. Strong training performance alone does not establish that a model generalizes. A large gap between training and validation performance can be a sign of overfitting, although the two periods may also differ in their conditions.
"""

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, r2_score

# Create Random Forest with the same settings as before.
rf_model = RandomForestRegressor(
    n_estimators=300,
    max_depth=6,
    min_samples_leaf=5,
    random_state=42,
    n_jobs=-1
)

# Train Random Forest using only 2023–2024 examples.
# Your existing Linear Regression remains stored in "model".
rf_model.fit(
    train_df[features],
    train_df["pm25_tomorrow"]
)

# Save validation predictions for your existing graph code.
rf_predictions = rf_model.predict(validation_df[features])

# Collect performance results for both periods.
results = []

for period, data in [
    ("Training: 2023–2024", train_df),
    ("Validation: 2025", validation_df)
]:
    # Actual next-day measurements for this period.
    actual_values = data["pm25_tomorrow"]

    # Predict identical examples with each approach.
    predictions = {
        "Persistence baseline": data["pm25"],
        "Linear Regression": model.predict(data[features]),
        "Random Forest": rf_model.predict(data[features])
    }

    # Calculate the baseline error used for the improvement comparison.
    baseline_error = mean_absolute_error(
        actual_values, predictions["Persistence baseline"]
    )

    for name, predicted_values in predictions.items():
        # MAE measures average absolute error in pollution units.
        mae = mean_absolute_error(actual_values, predicted_values)

        # Positive improvement means lower MAE than persistence.
        # Leave undefined if the baseline already has zero error.
        improvement = (
            100 * (baseline_error - mae) / baseline_error
            if baseline_error > 0 else float("nan")
        )

        results.append({
            "Period": period,
            "Approach": name,
            "Examples": len(data),
            "MAE (µg/m³)": mae,
            "R²": r2_score(actual_values, predicted_values),
            "MAE improvement vs baseline (%)": improvement
        })

# Convert the collected scores into a readable table.
comparison = pd.DataFrame(results)

# Show training results to help investigate fitting behavior.
print("TRAINING PERFORMANCE")
display(
    comparison[
        comparison["Period"] == "Training: 2023–2024"
    ].reset_index(drop=True).round(3)
)

# Use validation results to compare and choose approaches.
print("VALIDATION PERFORMANCE")
display(
    comparison[
        comparison["Period"] == "Validation: 2025"
    ].reset_index(drop=True).round(3)
)

"""## Step 7: Create the three-day history ensemble

Pollution may have patterns across consecutive days. We therefore add three features to the existing five:

| History feature | Definition for input day D |
| --- | --- |
| `pm25_yesterday` | PM2.5 on D−1. |
| `pm25_mean_3days` | Mean PM2.5 across D−2, D−1, and D. |
| `pm25_change` | PM2.5 on D minus PM2.5 on D−1. |

All history is constructed on the complete daily calendar before incomplete examples are removed. The three-day mean requires three measured days. We do not fill a missing history day with zero or replace it with the previous available observation.

We train a **new Linear Regression and a new Random Forest** on all eight features and average their predictions:

**History ensemble prediction = 0.5 × history regression prediction + 0.5 × history forest prediction.**

Both history components use the same history-eligible training rows. They are separate from the individual five-feature models. We compare all approaches on the same history-eligible validation targets. In the bundled snapshot, the history models have 652 training examples and 342 validation examples; the individual models have 674 training examples. This compares the final pipelines, rather than isolating the feature change with identical training rows.
"""

import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, r2_score

# Copy the complete daily calendar, preserving missing dates.
history_data = (
    combined.sort_values("date")
    .reset_index(drop=True)
    .copy()
)

# Confirm that each row represents the next calendar day.
if not history_data["date"].diff().dropna().eq(
    pd.Timedelta(days=1)
).all():
    raise ValueError("The dataset must contain every calendar day exactly once.")

# Add recent pollution history using only today and earlier dates.
history_data["pm25_yesterday"] = history_data["pm25"].shift(1)

history_data["pm25_mean_3days"] = (
    history_data["pm25"]
    .rolling(window=3, min_periods=3)
    .mean()
)

history_data["pm25_change"] = (
    history_data["pm25"] - history_data["pm25_yesterday"]
)

# Create tomorrow's target before removing incomplete rows.
history_data["pm25_tomorrow"] = history_data["pm25"].shift(-1)
history_data["target_date"] = (
    history_data["date"] + pd.Timedelta(days=1)
)

# Keep the original features and add history.
history_features = features + [
    "pm25_yesterday",
    "pm25_mean_3days",
    "pm25_change"
]

# Require all inputs and a real next-day target.
history_examples = history_data.dropna(
    subset=history_features + ["pm25_tomorrow"]
).copy()

# Keep the same chronological boundaries.
history_train = history_examples[
    history_examples["target_date"] < "2025-01-01"
].copy()

history_validation = history_examples[
    (history_examples["target_date"] >= "2025-01-01")
    & (history_examples["target_date"] < "2026-01-01")
].copy()

rf_settings = {
    "n_estimators": 300,
    "max_depth": 6,
    "min_samples_leaf": 5,
    "random_state": 42,
    "n_jobs": -1
}

# Train both components of the new ensemble with history.
history_lr_model = LinearRegression()
history_rf_model = RandomForestRegressor(**rf_settings)

history_lr_model.fit(
    history_train[history_features],
    history_train["pm25_tomorrow"]
)
history_rf_model.fit(
    history_train[history_features],
    history_train["pm25_tomorrow"]
)

# Average both history models to create the new ensemble prediction.
history_ensemble_predictions = (
    history_lr_model.predict(history_validation[history_features])
    + history_rf_model.predict(history_validation[history_features])
) / 2

# Compare all approaches on the same validation examples.
predictions = {
    "Persistence baseline": history_validation["pm25"],
    "Linear Regression": model.predict(history_validation[features]),
    "Random Forest": rf_model.predict(history_validation[features]),
    "Ensemble with history": history_ensemble_predictions
}

results = []

for name, predicted_values in predictions.items():
    results.append({
        "Approach": name,
        "Validation examples": len(history_validation),
        "MAE (µg/m³)": mean_absolute_error(
            history_validation["pm25_tomorrow"], predicted_values
        ),
        "R²": r2_score(
            history_validation["pm25_tomorrow"], predicted_values
        )
    })

print("History training examples:", len(history_train))
print("History validation examples:", len(history_validation))
display(pd.DataFrame(results).round(3))

