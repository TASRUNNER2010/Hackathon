"""## Step 3: Add weather information

This cell adds four weather measurements for the same location and dates:

| Weather feature | Daily measurement | Unit |
| --- | --- | --- |
| Temperature | Mean temperature | °C |
| Relative humidity | Mean humidity | % |
| Precipitation | Total precipitation | mm |
| Wind speed | Mean wind speed | m/s |

These inputs let the models learn associations between weather conditions and subsequent pollution. They do not establish that a particular weather variable causes a particular pollution change.

The code normally reuses the cached weather CSV. If the cache is absent, or `REFRESH_WEATHER` is set to `True`, it requests historical weather from Open-Meteo. Dates use the **America/New_York** timezone to match local calendar days.

Weather and pollution are joined by date with a one-to-one merge. Missing pollution dates remain in the calendar. The cell reports missing weather values and saves both the weather table and `airaware_epa_weather_2023_2026.csv`.

"""

import requests

# Use the first and last dates in the cleaned EPA dataset.
# strftime converts dates into the format Open-Meteo expects.
